import Combine
import SwiftUI

@MainActor final class DeckStore: ObservableObject {
  @Published var agents: [DeckAgent] = []
  @Published var source: CacheSource?
  @Published var error: String?
  @Published var loading = false
  @Published var endpoint =
    UserDefaults.standard.string(forKey: "bridgeEndpoint") ?? "http://127.0.0.1:43872"
  @Published var isPaired = false
  @Published var exampleMode = false
  @Published var certificateFingerprint = UserDefaults.standard.string(forKey: "bridgeCertificatePin") ?? ""
  @Published var lastRefresh: Date?
  @Published private(set) var liveEnabled = false
  @Published private(set) var pendingPrompts: [String: PendingPrompt] = [:]
  @Published private(set) var busyAgents: Set<String> = []
  @Published private(set) var avatars: [String: Data] = [:]
  @Published private(set) var computers: [DeckComputer] = []
  @Published private(set) var computersLoading = false
  @Published private(set) var computersComplete = true
  @Published private(set) var computersCheckedAt: Date?
  @Published private(set) var computersError: String?
  var isLive: Bool { source?.kind == "live-gateway" }
  private var client: BridgeClient?
  private var generation = 0
  private var pendingDevelopmentPairing = false
  private var avatarRequests: Set<String> = []
  private var missingAvatars: Set<String> = []
  init() {
    #if DEBUG
      if ProcessInfo.processInfo.arguments.contains("--ui-testing") {
        exampleMode = true
        isPaired = true
        let ms = Date().timeIntervalSince1970 * 1000
        liveEnabled = ProcessInfo.processInfo.arguments.contains("--ui-testing-live")
        if liveEnabled {
          source = CacheSource(kind: "live-gateway", available: true, checkedAt: ms,
            version: nil, cacheUpdatedAt: ms, warning: nil)
        }
        agents = [
          DeckAgent(
            id: "example-agent", name: "Research desk", description: "Example workspace",
            section: "Projects", hasUnread: true, awaitingResponse: false, lastActivityAt: ms,
            preview: "A useful starting point for your next idea.", messageCount: 2, cachedAt: ms)
        ]
        return
      }
      let environment = ProcessInfo.processInfo.environment
      if let token = environment["GROKDECK_BRIDGE_TOKEN"],
        let address = environment["GROKDECK_BRIDGE_URL"],
        let url = try? BridgeAddress.validate(address)
      {
        let pin = environment["GROKDECK_BRIDGE_CERT_SHA256"] ?? ""
        do {
          let normalized = try BridgeCertificate.normalizedPin(pin, endpoint: url)
          client = BridgeClient(baseURL: url, token: token, certificatePin: normalized)
          endpoint = address
          certificateFingerprint = normalized ?? ""
          isPaired = true
          pendingDevelopmentPairing = true
        } catch { self.error = error.localizedDescription }
        return
      }
    #endif
    if let token = PairingStore.read(), let url = try? BridgeAddress.validate(endpoint) {
      do {
        let pin = try BridgeCertificate.normalizedPin(certificateFingerprint, endpoint: url)
        client = BridgeClient(baseURL: url, token: token, certificatePin: pin)
        isPaired = true
      } catch { self.error = error.localizedDescription }
    }
  }
  func connectSetup(_ text: String) async -> Bool {
    guard !loading else { return false }
    loading = true
    defer { loading = false }
    do {
      let setup = try PhoneSetup.parse(text)
      let url = try BridgeAddress.validate(setup.endpoint)
      let candidate = BridgeClient(baseURL: url, token: setup.code, certificatePin: try BridgeCertificate.normalizedPin(setup.pin, endpoint: url))
      let response: EnrollmentResponse = try await candidate.post("v1/pair", body: [String: String](), as: EnrollmentResponse.self)
      guard response.apiVersion == 1 else { throw BridgeError.unsupported }
      return await connect(address: setup.endpoint, token: response.token, certificateFingerprint: setup.pin)
    } catch {
      self.error = "\(error.localizedDescription) Copy a new phone setup if it expired or was already used, and check both devices are on the same private network."
      return false
    }
  }
  func connect(address: String, token: String, certificateFingerprint: String = "") async -> Bool {
    guard token.range(of: "^[A-Za-z0-9_-]{43}$", options: .regularExpression) != nil else {
      error = "Enter the complete pairing key generated by your Mac bridge."
      return false
    }
    do {
      let url = try BridgeAddress.validate(address)
      let pin = try BridgeCertificate.normalizedPin(certificateFingerprint, endpoint: url)
      let candidate = BridgeClient(baseURL: url, token: token, certificatePin: pin)
      loading = true
      defer { loading = false }
      let health: BridgeHealth = try await candidate.get("v1/health", as: BridgeHealth.self)
      guard health.apiVersion == 1 else { throw BridgeError.unsupported }
      let response: AgentResponse = try await candidate.get("v1/agents", as: AgentResponse.self)
      guard response.apiVersion == 1 else { throw BridgeError.unsupported }
      try PairingStore.save(token)
      generation += 1
      client = candidate
      pendingDevelopmentPairing = false
      endpoint = url.absoluteString
      UserDefaults.standard.set(endpoint, forKey: "bridgeEndpoint")
      self.certificateFingerprint = pin ?? ""
      UserDefaults.standard.set(pin, forKey: "bridgeCertificatePin")
      agents = response.agents.sorted { $0.lastActivityAt > $1.lastActivityAt }
      source = response.source
      liveEnabled = health.canSend && response.source.kind == "live-gateway"
      error = nil
      isPaired = true
      lastRefresh = Date()
      return true
    } catch {
      self.error = error.localizedDescription
      return false
    }
  }
  func refresh() async {
    guard let client, !loading, !exampleMode else { return }
    let requestGeneration = generation
    loading = true
    defer { loading = false }
    do {
      let health: BridgeHealth = try await client.get("v1/health", as: BridgeHealth.self)
      guard health.apiVersion == 1 else { throw BridgeError.unsupported }
      let response: AgentResponse = try await client.get("v1/agents", as: AgentResponse.self)
      guard response.apiVersion == 1 else { throw BridgeError.unsupported }
      guard requestGeneration == generation else { return }
      if pendingDevelopmentPairing {
        // Developer launch inputs become persistent only after the authenticated
        // health and roster reads succeed, exactly like manual pairing.
        try PairingStore.save(client.token)
        UserDefaults.standard.set(endpoint, forKey: "bridgeEndpoint")
        UserDefaults.standard.set(certificateFingerprint.isEmpty ? nil : certificateFingerprint,
          forKey: "bridgeCertificatePin")
        pendingDevelopmentPairing = false
      }
      agents = response.agents.sorted { $0.lastActivityAt > $1.lastActivityAt }
      source = response.source
      liveEnabled = health.canSend && response.source.kind == "live-gateway"
      error = nil
      lastRefresh = Date()
    } catch {
      if requestGeneration == generation { self.error = error.localizedDescription; liveEnabled = false }
    }
  }
  func discussion(_ agent: DeckAgent) async throws -> DiscussionResponse {
    #if DEBUG
      if exampleMode {
        let ms = Date().timeIntervalSince1970 * 1000
        if ProcessInfo.processInfo.arguments.contains("--ui-testing-long-discussion") {
          let entries = (0..<20).map { index in
            DeckMessage(id: "example-long-\(index)", role: "assistant", author: nil,
              content: index == 19 ? "Latest example message" : "Earlier example message \(index). " + String(repeating: "Some earlier detail in this conversation. ", count: 8),
              timestamp: ms - Double(20 - index) * 1000, type: "text", streaming: false)
          }
          return DiscussionResponse(apiVersion: 1, agentId: agent.id, name: agent.name,
            cachedAt: ms, messages: entries,
            source: CacheSource(kind: liveEnabled ? "live-gateway" : "example", available: true,
              checkedAt: ms, version: nil, cacheUpdatedAt: ms, warning: nil))
        }
        var entries = [
            DeckMessage(
              id: "example-1", role: "user", author: nil,
              content: "Help me pick up where we left off.", timestamp: ms - 60000, type: "text",
              streaming: false),
            DeckMessage(
              id: "example-2", role: "assistant", author: nil,
              content:
                "This is example data for interface testing. Real discussions are read through your paired Mac bridge.",
              timestamp: ms, type: "text", streaming: false),
        ]
        if ProcessInfo.processInfo.arguments.contains("--ui-testing-emoji") {
          entries.append(DeckMessage(id: "example-emoji", role: "assistant", author: nil,
            content: "Emoji render check: 🙂 👍 ❤️ 🎉 🤔 👀", timestamp: ms, type: "text", streaming: false))
        }
        return DiscussionResponse(apiVersion: 1, agentId: agent.id, name: agent.name, cachedAt: ms,
          messages: entries,
          source: CacheSource(
            kind: liveEnabled ? "live-gateway" : "example", available: true, checkedAt: ms, version: nil, cacheUpdatedAt: ms,
            warning: nil))
      }
    #endif
    guard let client else { throw BridgeError.missingPairing }
    guard BridgeAddress.conversation(id: agent.id) != nil else { throw BridgeError.invalidResponse }
    let requestGeneration = generation
    let response: DiscussionResponse = try await client.get(
      "v1/agents/\(agent.id)/messages", as: DiscussionResponse.self)
    guard requestGeneration == generation else { throw BridgeError.missingPairing }
    guard response.apiVersion == 1 else { throw BridgeError.unsupported }
    guard response.agentId == agent.id else { throw BridgeError.invalidResponse }
    return response
  }
  func send(_ agent: DeckAgent, prompt: String, replyToId: String? = nil) async {
    let text = prompt.trimmingCharacters(in: .whitespacesAndNewlines)
    guard liveEnabled, !text.isEmpty, text.utf8.count <= 64 * 1024,
      BridgeAddress.conversation(id: agent.id) != nil,
      pendingPrompts[agent.id]?.blocksNewSend != true, !busyAgents.contains(agent.id)
    else { return }
    guard replyToId == nil || (replyToId?.isEmpty == false && (replyToId?.utf8.count ?? 0) <= 512) else { return }
    let pending = PendingPrompt(clientNonce: UUID().uuidString, prompt: text, state: .sending, replyToId: replyToId)
    pendingPrompts[agent.id] = pending
    busyAgents.insert(agent.id)
    let epoch = generation
    defer { busyAgents.remove(agent.id) }
    #if DEBUG
      if exampleMode {
        pendingPrompts[agent.id]?.state = ProcessInfo.processInfo.arguments.contains("--ui-testing-send-unknown") ? .unknown : .accepted
        return
      }
    #endif
    guard let client else { pendingPrompts[agent.id]?.state = .rejected; return }
    do {
      let receipt: BridgeSendReceipt = try await client.post("v1/agents/\(agent.id)/send",
        body: SendPromptBody(prompt: text, clientNonce: pending.clientNonce, replyToId: pending.replyToId), as: BridgeSendReceipt.self)
      guard epoch == generation else { return }
      pendingPrompts[agent.id]?.state = try checkedState(receipt, nonce: pending.clientNonce)
    } catch {
      guard epoch == generation else { return }
      // A lost response may follow a successful send. Preserve its original nonce and
      // prompt; never retry POST automatically or create a replacement nonce here.
      pendingPrompts[agent.id]?.state = knownRejection(error) ? .rejected : .unknown
    }
  }
  func acceptance(_ agent: DeckAgent) async {
    guard let pending = pendingPrompts[agent.id], pending.state == .unknown,
      !busyAgents.contains(agent.id) else { return }
    busyAgents.insert(agent.id)
    let epoch = generation
    defer { busyAgents.remove(agent.id) }
    #if DEBUG
      if exampleMode { pendingPrompts[agent.id]?.state = .accepted; return }
    #endif
    guard let client else { return }
    do {
      let receipt: BridgeSendReceipt = try await client.get(
        "v1/agents/\(agent.id)/sends/\(pending.clientNonce)", as: BridgeSendReceipt.self)
      guard epoch == generation else { return }
      pendingPrompts[agent.id]?.state = try checkedState(receipt, nonce: pending.clientNonce)
    } catch { /* Remain unknown. Checking status never resends a prompt. */ }
  }
  func interrupt(_ agent: DeckAgent) async throws {
    guard liveEnabled, let client, BridgeAddress.conversation(id: agent.id) != nil else { throw BridgeError.readOnly }
    let epoch = generation
    let response: InterruptResponse = try await client.post("v1/agents/\(agent.id)/interrupt", body: EmptyBridgeBody(), as: InterruptResponse.self)
    guard response.apiVersion == 1, epoch == generation else { throw BridgeError.invalidResponse }
  }
  func loadAvatar(_ id: String) async {
    guard isLive, !exampleMode, let client, BridgeAddress.conversation(id: id) != nil,
      avatars[id] == nil, !avatarRequests.contains(id), !missingAvatars.contains(id) else { return }
    let epoch = generation
    avatarRequests.insert(id)
    defer { if epoch == generation { avatarRequests.remove(id) } }
    do {
      let response: AvatarPayload = try await client.get("v1/agents/\(id)/avatar", as: AvatarPayload.self)
      guard epoch == generation else { return }
      guard let data = response.imageData() else { missingAvatars.insert(id); return }
      avatars[id] = data
    } catch BridgeError.http(404) {
      if epoch == generation { missingAvatars.insert(id) }
    } catch { /* Keep the initials fallback and retry when this row appears again. */ }
  }
  func refreshComputers() async {
    guard !computersLoading else { return }
    computersLoading = true
    defer { computersLoading = false }
    #if DEBUG
      if exampleMode {
        let now = Date().timeIntervalSince1970 * 1000
        computers = [
          DeckComputer(agentId: "example-agent", name: "Research desk", state: .running,
            windows: [ComputerWindow(index: 0, label: "Research browser")], checkedAt: now, error: nil),
          DeckComputer(agentId: "example-sleeping", name: "Sleeping example", state: .hibernated,
            windows: [], checkedAt: now, error: nil),
          DeckComputer(agentId: "example-unknown", name: "Unreachable example", state: .unknown,
            windows: [], checkedAt: now, error: "Status unavailable"),
        ]
        computersComplete = false; computersCheckedAt = Date(); computersError = nil
        return
      }
    #endif
    guard let client else { computersError = BridgeError.missingPairing.localizedDescription; return }
    let epoch = generation
    do {
      let response: ComputersResponse = try await client.get("v1/computers", as: ComputersResponse.self)
      guard response.apiVersion == 1 else { throw BridgeError.unsupported }
      guard epoch == generation else { return }
      computers = response.computers
      computersComplete = response.complete
      computersCheckedAt = Date(timeIntervalSince1970: response.checkedAt / 1000)
      computersError = nil
    } catch { if epoch == generation { computersError = error.localizedDescription } }
  }
  private func checkedState(_ receipt: BridgeSendReceipt, nonce: String) throws -> PromptState {
    guard receipt.apiVersion == 1, receipt.clientNonce == nonce else { throw BridgeError.invalidResponse }
    return receipt.state
  }
  private func knownRejection(_ error: Error) -> Bool {
    guard let error = error as? BridgeError else { return false }
    switch error {
    case .unauthorized: return true
    case .http(let status): return [400, 403, 404, 405, 413, 422].contains(status)
    default: return false
    }
  }
  func disconnect() {
    generation += 1
    client = nil
    pendingDevelopmentPairing = false
    liveEnabled = false
    pendingPrompts = [:]
    busyAgents = []
    avatars = [:]; avatarRequests = []; missingAvatars = []
    computers = []; computersComplete = true; computersCheckedAt = nil; computersError = nil
    PairingStore.clear()
    UserDefaults.standard.removeObject(forKey: "bridgeCertificatePin")
    certificateFingerprint = ""
    isPaired = false
    agents = []
    source = nil
    error = nil
    lastRefresh = nil
  }
}
